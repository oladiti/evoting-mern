/**
 * Print (or write) the Content-Security-Policy for a deployment where something
 * other than Express serves the page.
 *
 * Why this is needed: helmet only puts the policy on a response it handles. It
 * reaches the HTML at all only when the API also serves it, which app.js does
 * solely under NODE_ENV=production. A deployment where Apache (or nginx, or any
 * static host) serves client/dist and Express is API-only therefore ships with
 * no CSP on the document at all - every directive in server/src/config/csp.js
 * would apply to API responses only, where it does almost nothing, and the page
 * would be just as injectable as it was before the policy was written.
 *
 * So if the page is served separately, that server has to send the header
 * itself. This script exists so the value it sends comes from the same source as
 * the API's, rather than being copied by hand and left to rot.
 *
 * It also prints the report-uri consequence, which is the part that is easy to
 * miss: a report-uri is resolved against the *page's* origin. If the page and
 * the API are on different origins the report POST is cross-origin, which needs
 * the receiving origin in ALLOWED_ORIGINS and will silently fail otherwise. Same
 * origin for both is the arrangement to aim for.
 *
 * Usage (from server/):
 *   npm run csp:emit                              # print the policy and guidance
 *   npm run csp:emit -- --mode=enforce            # as it would be once enforcing
 *   npm run csp:emit -- --write=../client/dist/.htaccess   # emit Apache config
 */
import fs from 'fs';
import path from 'path';
import { policyHeaderValue, REPORT_URI } from '../src/config/csp.js';

function mode() {
  const arg = process.argv.find((a) => a.startsWith('--mode='));
  const value = arg ? arg.slice('--mode='.length) : 'report-only';
  if (!['off', 'report-only', 'enforce'].includes(value)) {
    throw new Error(`--mode must be report-only, enforce or off. Got "${value}".`);
  }
  return value;
}

const apacheBlock = (value) =>
  [
    '# Generated by server/scripts/emit-csp.mjs - do not hand-edit.',
    '# Edit server/src/config/csp.js and re-run; the same module feeds the API,',
    '# the Vite dev server and this file.',
    '#',
    '# Requires mod_headers (a2enmod headers on Debian/Ubuntu, LoadModule',
    '# headers_module in httpd.conf on XAMPP). Without it these lines are',
    '# silently ignored and the page is served with no policy at all.',
    '<IfModule mod_headers.c>',
    '  Header always set Content-Security-Policy "' + value.replace(/"/g, '\\"') + '"',
    '</IfModule>',
  ].join('\n');

const nginxBlock = (value) =>
  [
    '# Generated by server/scripts/emit-csp.mjs - do not hand-edit.',
    '# Add to the `server` block serving the built client.',
    '#',
    '# `always` so the header is present on error responses too.',
    '#',
    '# Note: the report-uri is resolved against the browser-visible origin, so the',
    '# page and the API need to share one, or the reports will not arrive.',
    // Double quotes, not single. The policy is full of 'self' and
    // 'unsafe-inline', and nginx cannot escape a single quote inside a
    // single-quoted string - the config would not parse. Double quotes need no
    // escaping for this value, which contains none.
    'add_header Content-Security-Policy "' + value.replace(/"/g, '\\"') + '" always;',
  ].join('\n');

function main() {
  const m = mode();

  if (m === 'off') {
    console.log('CSP_MODE=off - no policy is sent. Everything below is for reference.');
    console.log('');
  }

  const headerName = m === 'enforce' ? 'Content-Security-Policy' : 'Content-Security-Policy-Report-Only';
  const value = policyHeaderValue({ reportUri: m === 'off' ? null : REPORT_URI });

  console.log(`CSP_MODE            : ${m}`);
  console.log(`Header              : ${headerName}`);
  console.log(`Report endpoint     : ${REPORT_URI}`);
  console.log('');
  console.log('--- header value ---');
  console.log(value);
  console.log('');

  if (m === 'off') {
    console.log('Nothing to deploy. The lines below apply once CSP_MODE is report-only or enforce.');
    console.log('');
  }

  console.log('--- Apache (.htaccess) ---');
  console.log(apacheBlock(value));
  console.log('');
  console.log('--- nginx ---');
  console.log(nginxBlock(value));
  console.log('');

  const writeArg = process.argv.find((a) => a.startsWith('--write='));
  if (writeArg) {
    const target = path.resolve(writeArg.slice('--write='.length));
    // Writing to .htaccess is destructive in a way printing is not: it lands in
    // a directory the web server reads on every request, and a half-written
    // file there breaks the site. So the path is mandatory and explicit, and
    // existing content is never clobbered without --force.
    if (!fs.existsSync(path.dirname(target))) {
      throw new Error(`Refusing to write: ${path.dirname(target)} does not exist.`);
    }
    const force = process.argv.includes('--force');
    if (fs.existsSync(target) && !force) {
      throw new Error(`Refusing to overwrite ${target}. Re-run with --force if that is intended.`);
    }
    fs.writeFileSync(target, apacheBlock(value) + '\n', 'utf8');
    console.log(`written: ${target}`);
  } else {
    console.log('Nothing written. Pass --write=<path> to emit the Apache block to a file.');
  }

  if (m === 'report-only') {
    console.log('');
    console.log('Still in report-only: nothing is blocked. Before switching to enforce,');
    console.log('run `npm run build` and exercise register, login, face enrol, face verify,');
    console.log('vote, results, admin analytics and the contact form, then confirm this');
    console.log(`process logged no "[csp]" lines. Those go to stderr, not stdout - on a`);
    console.log(`service that keeps them apart, watch the error stream. The browser console`);
    console.log('alone is not enough: a report-only policy with no report-uri tells you');
    console.log('nothing unless a human happens to be watching devtools.');
  }
}

try {
  main();
} catch (err) {
  console.error(err.message);
  process.exit(1);
}
